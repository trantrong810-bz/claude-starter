#!/usr/bin/env node
// Workflow diagram index: each workflow is a file in docs/workflows/; docs/WORKFLOW.md is generated.
//
//   node scripts/workflow.mjs index   regenerate docs/WORKFLOW.md from the files' front matter
//   node scripts/workflow.mjs check   validate (runs in verify)
//
// New workflow: copy docs/workflows/_template.md to docs/workflows/<name>.md, fill it in, run index.

import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const DIR = "docs/workflows";
const INDEX = "docs/WORKFLOW.md";
const NAME = /^[a-z0-9]+(-[a-z0-9]+)*\.md$/;

function parse(file) {
  // Normalize CRLF: files may be checked out with CRLF on Windows.
  const text = readFileSync(join(DIR, file), "utf8").replace(/\r\n/g, "\n");
  const fm = text.match(/^---\n([\s\S]*?)\n---/);
  const meta = {};
  if (fm) {
    for (const line of fm[1].split("\n")) {
      const m = line.match(/^([a-z-]+):\s*(.*?)\s*(#.*)?$/);
      if (m) meta[m[1]] = m[2];
    }
  }
  return { file, meta, hasFrontmatter: !!fm };
}

function load() {
  if (!existsSync(DIR)) return [];
  return readdirSync(DIR)
    .filter((f) => f.endsWith(".md") && f !== "README.md" && !f.startsWith("_"))
    .map(parse)
    .sort(
      (a, b) =>
        (Number(a.meta.order) || 0) - (Number(b.meta.order) || 0) ||
        a.file.localeCompare(b.file),
    );
}

function renderIndex(flows) {
  const rows = flows.map(
    (w) =>
      `| ${w.meta.order ?? ""} | [${w.meta.title ?? w.file}](workflows/${w.file}) | ${w.meta.description ?? ""} |`,
  );
  return `# Working with Claude Code

> Generated by \`node scripts/workflow.mjs index\` — do not edit.
> The diagrams reflect the current configuration in \`.claude/\`. Changing a command, hook, subagent or the task classification rule → update the diagram in \`docs/workflows/\` in the same commit.

Yellow boxes are the points where you need to be present. Claude does every other step.

| # | Workflow | Description |
| --- | --- | --- |
${rows.join("\n")}

New workflow: copy \`workflows/_template.md\` to \`workflows/<name>.md\`, fill in the front matter and diagram, then run \`node scripts/workflow.mjs index\`.
`;
}

function check() {
  const flows = load();
  const errors = [];
  const byNo = new Map();
  for (const w of flows) {
    if (!NAME.test(w.file))
      errors.push(`${w.file}: file name must be lowercase kebab-case ASCII`);
    if (!w.hasFrontmatter) errors.push(`${w.file}: missing frontmatter`);
    const no = w.meta.order;
    if (!/^\d+$/.test(no ?? "")) errors.push(`${w.file}: order must be a number`);
    else if (byNo.has(no))
      errors.push(`${w.file}: order ${no} already used by ${byNo.get(no).file}`);
    else byNo.set(no, w);
    if (!w.meta.title) errors.push(`${w.file}: missing title`);
    if (!w.meta.description) errors.push(`${w.file}: missing description`);
  }
  // Compare ignoring table alignment whitespace (Prettier reformats the index).
  const norm = (s) =>
    s
      .split("\n")
      .map((l) =>
        l
          .trim()
          .replace(/\s*\|\s*/g, "|")
          .replace(/-{3,}/g, "---"),
      )
      .filter(Boolean)
      .join("\n");
  const expected = renderIndex(flows);
  if (
    !existsSync(INDEX) ||
    norm(readFileSync(INDEX, "utf8").replace(/\r/g, "")) !== norm(expected)
  )
    errors.push(
      `${INDEX}: index is out of date — run: node scripts/workflow.mjs index`,
    );
  if (errors.length) {
    console.error("WORKFLOW ERRORS:\n" + errors.map((e) => "- " + e).join("\n"));
    process.exit(1);
  }
}

const [cmd] = process.argv.slice(2);
if (cmd === "check") check();
else if (cmd === "index") writeFileSync(INDEX, renderIndex(load()));
else {
  console.log("Usage: node scripts/workflow.mjs <index|check>");
  process.exit(cmd ? 1 : 0);
}
