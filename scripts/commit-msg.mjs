#!/usr/bin/env node
// Validate commit messages against docs/GIT.md (Conventional Commits, English). No external dependencies.
//
//   node scripts/commit-msg.mjs <file>         git commit-msg hook (.githooks/commit-msg)
//   node scripts/commit-msg.mjs --message <m>  check one message
//   node scripts/commit-msg.mjs --command      read a bash command from stdin, take the message from -m/heredoc
//                                              (commit-guard.sh hook); skip if none can be extracted
//
// Exit 1 with errors on stderr when invalid.

import { readFileSync } from "node:fs";

const TYPES = ["feat", "fix", "refactor", "perf", "test", "docs", "style", "build", "ci", "chore", "revert"];
const HEADER = new RegExp(`^(${TYPES.join("|")})(\\(([a-z0-9][a-z0-9-]*)\\))?(!)?: (.+)$`);
const RELEASE = /^release: v\d+\.\d+\.\d+(-[0-9A-Za-z.-]+)?$/;
// Messages generated by git itself: accepted as is.
const GIT_GENERATED = /^(Merge |Revert "|fixup! |squash! |amend! )/;
const NOT_IMPERATIVE =
  /^(added|adds|fixed|fixes|updated|updates|removed|removes|changed|changes|created|creates|implemented|implements|refactored|refactors|renamed|renames|moved|moves|deleted|deletes|improved|improves)\b/i;
const MAX_HEADER = 72;
// Vietnamese letters (accented Latin, excluding × and ÷): messages are English (ADR 0020R).
const VIETNAMESE = /[\u00C0-\u00D6\u00D8-\u00F6\u00F8-\u1EF9]/;

function lint(message) {
  const lines = message
    .replace(/\r\n/g, "\n")
    .split("\n")
    .filter((l) => !l.startsWith("#")); // git comment lines
  while (lines.length && !lines[0].trim()) lines.shift();
  const header = lines[0] ?? "";
  if (!header.trim()) return ["empty message"];
  if (GIT_GENERATED.test(header) || RELEASE.test(header)) return [];

  const errors = [];
  const m = header.match(HEADER);
  if (!m) {
    errors.push(
      header.startsWith("release")
        ? `"release" is reserved for version.mjs: release: vX.Y.Z`
        : `header must look like <type>(<scope>): <subject>, type ∈ ${TYPES.join("|")}; scope in lowercase kebab-case`,
    );
  } else {
    const subject = m[5];
    if (/^[A-Z][a-z]/.test(subject)) errors.push(`subject starts with a lowercase letter: "${subject.split(" ")[0]}"`);
    if (NOT_IMPERATIVE.test(subject))
      errors.push(`subject uses the imperative ("add", not "added"/"adds"): "${subject.split(" ")[0]}"`);
    if (/[.。]$/.test(subject)) errors.push("subject does not end with a period");
    if (subject.trim().length < 3) errors.push("subject is too short");
  }
  if (header.length > MAX_HEADER) errors.push(`header is ${header.length} > ${MAX_HEADER} characters`);
  if (/[^\x20-\x7E]/.test(header)) errors.push("header must be ASCII (written in English)");
  else if (lines.some((l) => VIETNAMESE.test(l))) errors.push("message must be written in English");
  if (lines.length > 1 && lines[1].trim()) errors.push("line 2 must be blank (separates header from body)");
  return errors;
}

// Extract the message from a bash command: heredoc ($(cat <<'EOF' ... EOF)) or -m/--message (several -m = several paragraphs).
function messageFromCommand(cmd) {
  if (/(^|\s)(-F|--file)(=|\s)/.test(cmd)) return null;
  const heredoc = cmd.match(/<<-?\s*(['"]?)(\w+)\1[^\n]*\n([\s\S]*?)\n[ \t]*\2[ \t]*(\n|\)|$)/);
  if (heredoc) return heredoc[3];
  const parts = [];
  const re = /(?:^|\s)(?:-m|--message)(?:=|\s+)(?:"((?:[^"\\]|\\.)*)"|'([^']*)'|([^\s;&|]+))/g;
  for (const x of cmd.matchAll(re)) {
    parts.push(x[1] !== undefined ? x[1].replace(/\\(["\\$`])/g, "$1") : (x[2] ?? x[3]));
  }
  return parts.length ? parts.join("\n\n") : null;
}

function report(errors) {
  if (!errors.length) return;
  console.error(
    [
      "Commit message breaks the conventions (docs/GIT.md):",
      ...errors.map((e) => "- " + e),
      "Example: feat(todos): add contract, stub and failing tests",
      "         fix(shared): encode query params in listTodos",
    ].join("\n"),
  );
  process.exitCode = 1;
}

const [arg, value] = process.argv.slice(2);
if (arg === "--message") report(lint(value ?? ""));
else if (arg === "--command") {
  let s = "";
  process.stdin.on("data", (d) => (s += d)).on("end", () => {
    const msg = messageFromCommand(s);
    if (msg !== null) report(lint(msg));
  });
} else if (arg) report(lint(readFileSync(arg, "utf8")));
else {
  console.log("Usage: node scripts/commit-msg.mjs <file> | --message <m> | --command (stdin)");
}
