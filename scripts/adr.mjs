#!/usr/bin/env node
// Manage ADRs (Architecture Decision Records) in docs/decisions/. No external dependencies.
//
//   node scripts/adr.mjs new <slug> [--broad] [--model <id>]  create a new ADR from the template, next number
//   node scripts/adr.mjs index                                 regenerate docs/decisions/README.md
//   node scripts/adr.mjs check                                 validate (runs in verify)
//
// Broad decisions (≥2 parts, change a shared process/contract, or hard to reverse):
// scope: broad, file name has an R (0003R-name.md), listed in their own table at the top of the index.

import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const DIR = "docs/decisions";
const INDEX = join(DIR, "README.md");
const TEMPLATE = join(DIR, "_template.md");
const NAME = /^(\d{4})(R?)-([a-z0-9-]+)\.md$/;
const STATUSES = { proposed: "Proposed", accepted: "Accepted", superseded: "Superseded" };
const SCOPES = ["broad", "feature"];

function parse(file) {
  // Normalize CRLF: files may be checked out with CRLF on Windows.
  const text = readFileSync(join(DIR, file), "utf8").replace(/\r\n/g, "\n");
  const fm = text.match(/^---\n([\s\S]*?)\n---/);
  const meta = {};
  if (fm) {
    for (const line of fm[1].split("\n")) {
      const m = line.match(/^([a-z-]+):\s*(.*?)\s*(#.*)?$/);
      if (m) meta[m[1]] = m[2];
    }
  }
  const title = (text.match(/^# (.+)$/m) ?? [])[1] ?? "(untitled)";
  return { file, meta, title, hasFrontmatter: !!fm };
}

function load() {
  if (!existsSync(DIR)) return [];
  return readdirSync(DIR)
    .filter((f) => f.endsWith(".md") && f !== "README.md" && !f.startsWith("_"))
    .sort()
    .map(parse);
}

function renderIndex(adrs) {
  const row = (a) => {
    const st = STATUSES[a.meta.status] ?? a.meta.status;
    const title = a.meta.status === "superseded" ? `~~${a.title}~~` : a.title;
    const by = a.meta["superseded-by"] ? ` → ${a.meta["superseded-by"]}` : "";
    return `| ${a.meta.number} | [${title}](${a.file}) | ${st}${by} | ${a.meta.date ?? ""} | ${a.meta.model ?? ""} |`;
  };
  const table = (list) =>
    list.length
      ? [
          "| No. | Decision | Status | Date | Model |",
          "| --- | --- | --- | --- | --- |",
          ...list.map(row),
        ].join("\n")
      : "_None yet._";
  const broad = adrs.filter((a) => a.meta.scope === "broad");
  const feature = adrs.filter((a) => a.meta.scope !== "broad");
  return `# Decisions (ADR)

> Generated by \`node scripts/adr.mjs index\` — do not edit.
> Every contested decision has an ADR. Quick lookup: \`/why <question>\`.

## Broad (R)

Affects two or more parts, changes a shared process or contract, or is hard to reverse.

${table(broad)}

## Feature level

${table(feature)}
`;
}

function check() {
  const adrs = load();
  const errors = [];
  const byNo = new Map();
  for (const a of adrs) {
    const m = a.file.match(NAME);
    if (!m) {
      errors.push(`${a.file}: file name must look like 0001-name.md or 0001R-name.md`);
      continue;
    }
    if (!a.hasFrontmatter) errors.push(`${a.file}: missing frontmatter`);
    const [, no, r] = m;
    if (a.meta.number !== no) errors.push(`${a.file}: number (${a.meta.number}) does not match the file name (${no})`);
    if (byNo.has(no)) errors.push(`${a.file}: number ${no} already used by ${byNo.get(no).file}`);
    byNo.set(no, a);
    if (!SCOPES.includes(a.meta.scope)) errors.push(`${a.file}: scope must be broad or feature`);
    if ((a.meta.scope === "broad") !== (r === "R"))
      errors.push(`${a.file}: the R in the file name must match scope: broad`);
    if (!STATUSES[a.meta.status])
      errors.push(`${a.file}: status must be ${Object.keys(STATUSES).join(" | ")}`);
    if (!a.meta.model) errors.push(`${a.file}: missing model (the model that made the decision)`);
    if (!/^\d{4}-\d{2}-\d{2}$/.test(a.meta.date ?? "")) errors.push(`${a.file}: date must be YYYY-MM-DD`);
  }
  for (const a of adrs) {
    const by = a.meta["superseded-by"];
    if (a.meta.status === "superseded") {
      const target = byNo.get(by);
      if (!target)
        errors.push(`${a.file}: superseded but superseded-by (${by || "empty"}) does not point to an existing ADR`);
      else if (target.meta.status === "superseded" && !target.meta["superseded-by"])
        errors.push(`${a.file}: replacement ADR ${by} is itself superseded without pointing further`);
    } else if (by) {
      errors.push(`${a.file}: has superseded-by but status is not superseded`);
    }
  }
  // Compare ignoring table alignment whitespace (Prettier reformats the index).
  const norm = (s) =>
    s
      .split("\n")
      .map((l) =>
        l
          .trim()
          .replace(/\s*\|\s*/g, "|")
          .replace(/-{3,}/g, "---"),
      )
      .filter(Boolean)
      .join("\n");
  const expected = renderIndex(adrs);
  if (!existsSync(INDEX) || norm(readFileSync(INDEX, "utf8").replace(/\r/g, "")) !== norm(expected))
    errors.push(`${INDEX}: index is out of date — run: node scripts/adr.mjs index`);
  if (errors.length) {
    console.error("ADR ERRORS:\n" + errors.map((e) => "- " + e).join("\n"));
    process.exit(1);
  }
}

function create(args) {
  const slug = args.find((a) => !a.startsWith("--") && args[args.indexOf(a) - 1] !== "--model");
  if (!slug || !/^[a-z0-9-]+$/.test(slug)) {
    console.error("Usage: node scripts/adr.mjs new <lowercase-slug> [--broad] [--model <id>]");
    process.exit(1);
  }
  const broad = args.includes("--broad");
  const model = args.includes("--model") ? args[args.indexOf("--model") + 1] : "";
  const adrs = load();
  const next = String(Math.max(0, ...adrs.map((a) => Number(a.meta.number) || 0)) + 1).padStart(4, "0");
  const file = `${next}${broad ? "R" : ""}-${slug}.md`;
  const today = new Date().toLocaleDateString("sv-SE");
  const body = readFileSync(TEMPLATE, "utf8")
    .replace("number: 0000", `number: ${next}`)
    .replace("scope: feature", `scope: ${broad ? "broad" : "feature"}`)
    .replace("date: YYYY-MM-DD", `date: ${today}`)
    .replace(/^model:.*$/m, `model: ${model}`);
  writeFileSync(join(DIR, file), body);
  writeFileSync(INDEX, renderIndex(load()));
  console.log(join(DIR, file));
}

const [cmd, ...args] = process.argv.slice(2);
if (cmd === "check") check();
else if (cmd === "index") writeFileSync(INDEX, renderIndex(load()));
else if (cmd === "new") create(args);
else {
  console.log("Usage: node scripts/adr.mjs <new|index|check>");
  process.exit(cmd ? 1 : 0);
}
