#!/usr/bin/env node
// Todo per part, two layers. No external dependencies.
//
//   docs/todo/<part>.md        written by hand. The script never writes this file.
//   docs/todo/<part>.auto.md   written by Claude (In progress, To do, Recently done) + a generated "From manual" section.
//   TODO.md                    overview of all parts, fully generated.
//
//   node scripts/todo.mjs sync     sync manual → auto, then regenerate TODO.md. Safe to rerun.
//   node scripts/todo.mjs check    are TODO.md and the "From manual" sections in sync (runs in verify)
//   node scripts/todo.mjs brief    a few lines for the SessionStart hook: totals + work in progress
//
// The only convention in a manual file: a task is a "- [ ] ..." line (done: "- [x] ..."), "[P1]" optional.
// Work started from a manual task: the "In progress" item uses that task's exact text as its title, plus
// "from: [be.md#L12](be.md#L12)". sync finds it again by text when line numbers drift; once the original
// is [x] the item moves to "Recently done".

import { execSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { posix } from "node:path";

const { join } = posix;

try {
  process.chdir(
    execSync("git rev-parse --show-toplevel", {
      stdio: ["ignore", "pipe", "ignore"],
    })
      .toString()
      .trim(),
  );
} catch {}

const SCOPES = ["root", "shared", "be", "fe", "mobile"];
const DIR = "docs/todo";
const OVERVIEW = "TODO.md";
const DONE_MAX = 10;
const MIRROR_START =
  "<!-- todo:manual:start — generated by node scripts/todo.mjs sync, do not edit -->";
const MIRROR_END = "<!-- todo:manual:end -->";
const OPEN = /^\s*- \[ \] (.*)$/;
const CLOSED = /^\s*- \[[xX]\] (.*)$/;
const FROM = /from: \[([a-z]+\.md)#L(\d+)\]\([^)]*\)/;
const GONE = " (original task was removed from the manual file)";

const manualPath = (s) => join(DIR, `${s}.md`);
const autoPath = (s) => join(DIR, `${s}.auto.md`);
const readText = (file) =>
  existsSync(file) ? readFileSync(file, "utf8").replace(/\r\n/g, "\n") : null;
// A task's text without priority and extra whitespace — used to match manual tasks to "In progress" items.
const key = (text) =>
  text
    .replace(/\[P\d\]/g, "")
    .replace(/\s+/g, " ")
    .trim();
const title = (text) => text.split(" — ")[0].trim();
const branchOf = (text) => (text.match(/branch: ([^\s·]+)/) ?? [])[1];

const manualSkeleton = (s) => `# Manual todo: ${s}

Write freely, in any language. A task is a \`- [ ] ...\` line (add \`[P1]\` if urgent); tick \`[x]\` when done. Claude only reads this file.
`;

const autoSkeleton = (s) => `# Auto todo: ${s}

← [Overview](../../TODO.md) · Manual: [${s}.md](${s}.md)

## From manual

${MIRROR_START}
${MIRROR_END}

## In progress

## To do

## Recently done
`;

// --- Read ---

function manualItems(s) {
  const lines = (readText(manualPath(s)) ?? "").split("\n");
  const items = [];
  lines.forEach((line, i) => {
    const open = line.match(OPEN);
    const closed = line.match(CLOSED);
    if (open) items.push({ line: i + 1, text: open[1].trim(), done: false });
    else if (closed)
      items.push({ line: i + 1, text: closed[1].trim(), done: true });
  });
  return items;
}

// The "## ..." sections of an auto file: { name, start, end } as line indexes (end exclusive).
function sections(lines) {
  const out = [];
  lines.forEach((line, i) => {
    if (line.startsWith("## ")) {
      if (out.length) out.at(-1).end = i;
      out.push({ name: line.slice(3).trim(), start: i + 1, end: lines.length });
    }
  });
  return out;
}

// Top-level "- [ ] ..." items in a section, with their indented continuation lines.
function blocks(lines, sec) {
  const out = [];
  if (!sec) return out;
  for (let i = sec.start; i < sec.end; i++) {
    const line = lines[i];
    if (/^- \[[ xX]\] /.test(line)) out.push({ head: i, end: i + 1 });
    else if (out.length && /^\s+\S/.test(line) && out.at(-1).end === i)
      out.at(-1).end = i + 1;
  }
  return out;
}

function autoStats(s) {
  const lines = (readText(autoPath(s)) ?? "").split("\n");
  const secs = sections(lines);
  const get = (name) => secs.find((x) => x.name === name);
  const openIn = (name) =>
    blocks(lines, get(name))
      .map((b) => lines[b.head])
      .filter((l) => l.startsWith("- [ ] "))
      .map((l) => l.slice(6).trim());
  return { wip: openIn("In progress"), todo: openIn("To do") };
}

// --- Sync manual → auto ---

function mirrorLines(s, items) {
  const open = items.filter((it) => !it.done);
  const p1 = open.filter((it) => /\[P1\]/.test(it.text));
  const rest = open.filter((it) => !/\[P1\]/.test(it.text));
  return [...p1, ...rest].map(
    (it) => `- ${it.text} — [${s}.md#L${it.line}](${s}.md#L${it.line})`,
  );
}

function syncAuto(s, today) {
  const file = autoPath(s);
  let text = readText(file) ?? autoSkeleton(s);
  const items = manualItems(s);

  // "From manual" section: replace everything between the markers.
  const mirror = mirrorLines(s, items);
  const a = text.indexOf(MIRROR_START);
  const b = text.indexOf(MIRROR_END);
  if (a === -1 || b === -1) {
    text = text.replace(
      /\n## /,
      `\n## From manual\n\n${MIRROR_START}\n${MIRROR_END}\n\n## `,
    );
  }
  const start = text.indexOf(MIRROR_START) + MIRROR_START.length;
  text =
    text.slice(0, start) +
    "\n" +
    (mirror.length ? "\n" + mirror.join("\n") + "\n\n" : "") +
    text.slice(text.indexOf(MIRROR_END));

  // "In progress" items pointing at the manual file: fix line numbers, move to done once the original is [x].
  const lines = text.split("\n");
  const secs = sections(lines);
  const wipSec = secs.find((x) => x.name === "In progress");
  const doneSec = secs.find((x) => x.name === "Recently done");
  const finished = [];
  for (const blk of blocks(lines, wipSec)) {
    const head = lines[blk.head];
    const from = head.match(FROM);
    if (!from || from[1] !== `${s}.md` || !head.startsWith("- [ ] ")) continue;
    const t = key(title(head.slice(6)));
    const at = items.find(
      (it) => it.line === Number(from[2]) && key(it.text) === t,
    );
    const found = at ?? items.find((it) => key(it.text) === t);
    if (!found) {
      if (!head.includes(GONE)) lines[blk.head] = head + GONE;
      continue;
    }
    lines[blk.head] = head
      .replace(FROM, `from: [${s}.md#L${found.line}](${s}.md#L${found.line})`)
      .replace(GONE, "");
    if (found.done) finished.push(blk);
  }
  if (finished.length && doneSec) {
    const moved = finished.map(
      (blk) =>
        `- [x] ${title(lines[blk.head].slice(6))} (${today}, ticked in ${s}.md)`,
    );
    // Remove bottom-up so indexes stay valid, then insert at the top of the done section.
    for (const blk of [...finished].reverse())
      lines.splice(blk.head, blk.end - blk.head);
    const secs2 = sections(lines);
    const done2 = secs2.find((x) => x.name === "Recently done");
    const old = blocks(lines, done2).map((blk) =>
      lines.slice(blk.head, blk.end).join("\n"),
    );
    const kept = [...moved, ...old].slice(0, DONE_MAX);
    lines.splice(done2.start, done2.end - done2.start, "", ...kept, "");
  }
  text = tidy(lines.join("\n"));
  return { file, text };
}

// Exactly one blank line between blocks and around headings — like Prettier, so sync leaves no diff noise.
function tidy(text) {
  const out = [];
  for (const line of text.split("\n")) {
    const blank = line.trim() === "";
    if (blank && (out.length === 0 || out.at(-1) === "")) continue;
    if (line.startsWith("#") && out.length && out.at(-1) !== "") out.push("");
    if (!blank && out.length && out.at(-1).startsWith("#")) out.push("");
    out.push(blank ? "" : line);
  }
  while (out.at(-1) === "") out.pop();
  return out.join("\n") + "\n";
}

// --- TODO.md ---

function overview() {
  const rows = SCOPES.map((s) => {
    const manual = manualItems(s).filter((it) => !it.done);
    const { wip, todo } = autoStats(s);
    const p1 = [...manual.map((it) => it.text), ...wip, ...todo].filter((t) =>
      /\[P1\]/.test(t),
    ).length;
    const doing = wip.length
      ? `${key(title(wip[0]))}${branchOf(wip[0]) ? ` (${branchOf(wip[0])})` : ""}${wip.length > 1 ? ` +${wip.length - 1}` : ""}`
      : "—";
    return {
      cells: [
        s,
        `[${s}.md](docs/todo/${s}.md)`,
        `[${s}.auto.md](docs/todo/${s}.auto.md)`,
        String(wip.length),
        String(manual.length),
        String(todo.length),
        String(p1),
        doing.replace(/\|/g, "\\|"),
      ],
      wip: wip.length,
      manual: manual.length,
      todo: todo.length,
      p1,
    };
  });
  const sum = (k) => rows.reduce((n, r) => n + r[k], 0);
  const table = [
    [
      "Part",
      "Manual",
      "Auto",
      "WIP",
      "Manual todo",
      "Auto todo",
      "P1",
      "In progress",
    ],
    ...rows.map((r) => r.cells),
    [
      "**Total**",
      "",
      "",
      `**${sum("wip")}**`,
      `**${sum("manual")}**`,
      `**${sum("todo")}**`,
      `**${sum("p1")}**`,
      "",
    ],
  ];
  return `# Todo — overview

> Generated by \`node scripts/todo.mjs sync\` — do not edit. Edit each part's manual or auto file instead.

${markdownTable(table)}

## How to use

- **Manual**: \`docs/todo/<part>.md\` — yours, free-form and in any language; a task is a \`- [ ] ...\` line (\`[P1]\` if urgent). Claude only reads it and may only tick \`[x]\` when done.
- **Auto**: \`docs/todo/<part>.auto.md\` — Claude records work in progress (where it stopped, next step), newly found tasks and finished work. The "From manual" section mirrors the open tasks of the manual file.
- Committing a manual file → the hook syncs the auto file and \`TODO.md\` into the same commit.
- \`/todo\` view/add tasks · \`/handoff\` before switching machine or account (saves WIP, pushes unfinished code to \`wip/<branch>\`) · new machine: \`git pull\` then \`/resume\`.
`;
}

// Column-aligned table like Prettier (width = character count after NFC) so formatting leaves the file unchanged.
function markdownTable(rows) {
  const width = (s) => [...s.normalize("NFC")].length;
  const cols = rows[0].map((_, c) =>
    Math.max(3, ...rows.map((r) => width(r[c]))),
  );
  const line = (r) =>
    "| " +
    r.map((cell, c) => cell + " ".repeat(cols[c] - width(cell))).join(" | ") +
    " |";
  return [
    line(rows[0]),
    "| " + cols.map((w) => "-".repeat(w)).join(" | ") + " |",
    ...rows.slice(1).map(line),
  ].join("\n");
}

// Compare ignoring alignment spaces/dashes — Prettier may align slightly differently.
const loose = (t) =>
  (t ?? "")
    .replace(/-{3,}/g, "---")
    .replace(/[ \t]+/g, " ")
    .replace(/\n+/g, "\n")
    .trim();

// --- Commands ---

function sync(only) {
  if (!existsSync(DIR)) mkdirSync(DIR, { recursive: true });
  const today = new Date().toISOString().slice(0, 10);
  const changed = [];
  for (const s of SCOPES) {
    if (!existsSync(manualPath(s))) {
      writeFileSync(manualPath(s), manualSkeleton(s));
      changed.push(manualPath(s));
    }
    if (only.length && !only.includes(s) && existsSync(autoPath(s))) continue;
    const { file, text } = syncAuto(s, today);
    if (text !== readText(file)) {
      writeFileSync(file, text);
      changed.push(file);
    }
  }
  const text = overview();
  if (loose(text) !== loose(readText(OVERVIEW))) {
    writeFileSync(OVERVIEW, text);
    changed.push(OVERVIEW);
  }
  console.log(
    changed.length ? `Updated: ${changed.join(", ")}` : "Todo is in sync.",
  );
}

function check() {
  const errors = [];
  for (const s of SCOPES) {
    if (!existsSync(manualPath(s)) || !existsSync(autoPath(s))) {
      errors.push(`missing ${manualPath(s)} or ${autoPath(s)}`);
      continue;
    }
    const cur = readText(autoPath(s));
    const want = mirrorLines(s, manualItems(s)).join("\n");
    const a = cur.indexOf(MIRROR_START);
    const b = cur.indexOf(MIRROR_END);
    const have =
      a === -1 || b === -1 ? null : cur.slice(a + MIRROR_START.length, b);
    if (have === null || loose(have) !== loose(want))
      errors.push(`${autoPath(s)}: "From manual" section is out of sync with ${s}.md`);
  }
  if (loose(readText(OVERVIEW)) !== loose(overview()))
    errors.push(`${OVERVIEW} is out of sync with docs/todo/`);
  if (errors.length) {
    console.error("Todo out of sync — run: node scripts/todo.mjs sync");
    for (const e of errors) console.error(`- ${e}`);
    process.exit(1);
  }
}

function brief() {
  let wipTotal = 0;
  let todoTotal = 0;
  const lines = [];
  for (const s of SCOPES) {
    const { wip, todo } = autoStats(s);
    const manual = manualItems(s).filter((it) => !it.done).length;
    wipTotal += wip.length;
    todoTotal += todo.length + manual;
    for (const w of wip)
      lines.push(
        `- [${s}] ${title(w)}${branchOf(w) ? ` (branch ${branchOf(w)})` : ""}`,
      );
  }
  if (!wipTotal && !todoTotal) return;
  console.log(
    `Todo: ${wipTotal} in progress, ${todoTotal} waiting — overview in TODO.md.`,
  );
  for (const l of lines) console.log(l);
}

const [cmd, ...args] = process.argv.slice(2);
if (cmd === "sync") sync(args.filter((a) => SCOPES.includes(a)));
else if (cmd === "check") check();
else if (cmd === "brief") brief();
else {
  console.error("Usage: node scripts/todo.mjs sync [part...] | check | brief");
  process.exit(1);
}
